UMBRELLA = """CHIẾC Ô CHUNG

Chiều thứ sáu, khi tiếng trống tan học vừa dứt, mưa đổ xuống sân trường. Những vệt nước nối nhau chạy trên mái hiên. Minh mở chiếc ô xanh mẹ đã chuẩn bị rồi định bước ra cổng. Em muốn về sớm để kịp giúp ông tưới mấy chậu cây, nhưng hôm nay khu vườn chắc chẳng cần thêm nước.

Ở cuối hành lang, An ôm chồng vở đứng chờ. Bạn quên mang áo mưa và sợ những trang giấy bị ướt. Minh nhìn chiếc ô của mình. Ô không rộng lắm, nếu hai người đi sát nhau thì vẫn che được. Em quay lại, nói: “Mình cùng đi đến nhà chờ xe buýt nhé.” An mỉm cười, cất vở vào túi và bước bên cạnh bạn.

Đến đoạn đường có một vũng nước lớn, Minh nghiêng ô về phía An. Một bên vai áo em dần sẫm lại. An nhận ra, liền đề nghị đổi chỗ và cùng giữ cán ô. Hai bạn bước chậm, tránh làm nước bắn vào người khác. Khi gặp một em nhỏ đứng nép bên cửa hàng, các bạn dừng lại hỏi. Em chỉ cần qua đoạn đường ngắn để đến chỗ mẹ đang đợi.

Minh và An đưa em nhỏ đến dưới mái hiên rồi mới tiếp tục đi. Chuyến xe buýt của An vừa đến. Bạn cảm ơn và đưa Minh chiếc khăn sạch trong túi. Minh lau vai áo, nhìn theo chiếc xe rồi quay về nhà.

Ông thấy cháu về muộn, hỏi có chuyện gì. Minh kể lại, hơi lo vì đã làm ướt áo. Ông treo chiếc ô lên móc, bảo cháu thay áo khô. Nghe tiếng mưa rơi, Minh chợt thấy chiếc ô nhỏ đã che được nhiều hơn em tưởng. Nó che những cuốn vở, một quãng đường và cả nỗi lo của những người bạn."""

SEEDLING = """MẦM CÂY BÊN CỬA

Lớp Năm có một chiếc hộp gỗ đặt cạnh cửa sổ. Cô giáo mang đến ba hạt đậu và giao các bạn chăm cây trong hai tuần. Lan nhận việc ghi nhật kí. Em vẽ bảng có ba cột: ngày quan sát, việc đã làm và điều nhìn thấy. Mỗi buổi sáng, cả nhóm kiểm tra đất rồi mới quyết định có cần tưới hay không.

Ngày đầu, Tuấn muốn đổ đầy một cốc nước vào hộp. Lan nhớ lời cô dặn rằng hạt cũng cần không khí. Em đề nghị dùng thìa nhỏ, tưới vừa đủ ẩm. Tuấn chưa đồng ý ngay, nhưng khi xem hướng dẫn, bạn cùng Lan chia lượng nước thành từng phần. Hộp được đặt ở nơi sáng, tránh nắng gắt buổi trưa.

Ba ngày trôi qua, mặt đất vẫn im lìm. Một bạn bảo hạt chắc đã hỏng và định đào lên xem. Lan không vội kết luận. Em ghi vào nhật kí rằng chưa nhìn thấy mầm, rồi rủ nhóm giữ cách chăm sóc và quan sát thêm. Cô giáo nhắc các bạn phân biệt điều đã thấy với điều đang đoán. Câu nói ấy khiến Lan sửa dòng “hạt không mọc” thành “hôm nay chưa thấy mầm”.

Sáng thứ năm, một chấm xanh xuất hiện. Đến cuối tuần, hai mầm khác cũng nhô lên. Nhóm reo vui nhưng không quên kiểm tra đất và xoay hộp để các cây nhận ánh sáng. Tuấn vẽ những chiếc lá đầu tiên, còn Lan đo chiều cao bằng thước và ghi đơn vị xăng-ti-mét.

Trong buổi giới thiệu, Lan không chỉ kể cây đã cao bao nhiêu. Em kể cả lần nhóm suýt tưới quá nhiều và việc sửa một câu trong nhật kí. Các bạn nhận ra chăm cây cũng giống học tập: cần thử, quan sát, trao đổi và kiên nhẫn. Chiếc hộp nhỏ vẫn ở bên cửa, nhưng cuốn nhật kí đã giữ lại một bài học lớn."""

RAIN = """VÌ SAO CÓ MƯA?

Nước trên mặt đất luôn tham gia một vòng tuần hoàn. Khi nhận nhiệt từ Mặt Trời, một phần nước ở ao, hồ, sông và biển chuyển thành hơi nước. Hơi nước đi vào không khí; cây cối cũng góp phần đưa nước vào không khí qua lá. Quá trình này thường khó nhìn thấy bằng mắt.

Lên cao, không khí lạnh hơn. Hơi nước ngưng tụ thành những giọt rất nhỏ hoặc tinh thể băng, tập hợp thành mây. Mây không phải là một túi lớn đựng nước. Trong mây có vô số giọt nhỏ. Khi các giọt kết hợp và đủ lớn, chúng rơi xuống, tạo thành mưa.

Nước mưa có thể chảy vào sông, thấm vào đất hoặc được cây sử dụng. Sau đó, nước tiếp tục bốc hơi và tham gia vòng tuần hoàn mới. Các giai đoạn không tách rời nhau như những hộp kín; chúng diễn ra ở nhiều nơi trong cùng thời gian.

Hiểu vòng tuần hoàn giúp chúng ta thấy nước cần được giữ sạch. Rác hoặc chất bẩn thải vào nguồn nước có thể gây hại cho sinh vật và con người. Một việc nhỏ như bỏ rác đúng nơi, tiết kiệm nước khi rửa tay cũng góp phần bảo vệ nguồn nước quanh trường và ở nhà. Các bạn có thể ghi sơ đồ để nhớ."""

SCENERY = """SÂN TRƯỜNG SAU MƯA

Sau cơn mưa đêm, sân trường sáng lên như vừa được lau sạch. Những viên gạch đỏ còn giữ vài vệt nước nhỏ. Từ cổng nhìn vào, em thấy hàng bằng lăng đứng yên, trên lá có những giọt nước trong veo. Khi một làn gió nhẹ đi qua, mấy giọt rơi xuống, khẽ chạm mặt đất.

Góc vườn bên thư viện có mùi đất ẩm. Những chậu hoa được xếp ngay ngắn, màu vàng chen giữa màu tím. Một chú chim sẻ nhảy trên bờ tường rồi nghiêng đầu nhìn xuống. Tiếng chổi của bác lao công đi đều trên lối nhỏ. Bác gom lá rụng vào giỏ, để đường đến lớp không còn trơn.

Ít phút sau, sân trường đông hơn. Bạn nào cũng bước cẩn thận qua chỗ còn ướt. Tiếng chào nhau và tiếng mở cửa lớp làm buổi sáng trở nên rộn ràng. Ánh nắng đầu tiên chạm vào mái hiên, khiến những giọt nước còn sót lại lấp lánh.

Em thích sân trường lúc ấy vì vẻ quen thuộc bỗng có thêm nhiều điều đáng nhìn. Không cần đi xa, em vẫn tìm được một bức tranh đẹp ngay nơi mình học mỗi ngày. Em nhắc mình giữ sân sạch để ngày mai các bạn cũng được đón một buổi sáng trong lành."""

PERSON = """NGƯỜI GIỮ GÓC SÁCH

Cô Hạnh phụ trách thư viện nhỏ của trường em. Cô không nói lớn, nhưng lời hướng dẫn lúc nào cũng rõ ràng. Mái tóc cô thường được buộc gọn; đôi kính mảnh nằm ngay ngắn trên khuôn mặt hay cười. Khi có bạn mới đến, cô kéo ghế để bạn dễ nhìn những kệ sách thấp.

Điều em nhớ nhất là cách cô lắng nghe. Một hôm, em trả cuốn truyện và thú nhận rằng có đoạn chưa hiểu. Cô không vội kể hộ nội dung. Cô hỏi em đã chú ý chi tiết nào, rồi chỉ một câu để em đọc lại. Em tìm được lời giải trong trang sách và thấy vui vì mình tự làm được.

Giờ ra chơi, cô hướng dẫn cả nhóm dán nhãn những cuốn sách mới. Cô đưa mỗi bạn một việc vừa sức, nhắc đặt sách nhẹ tay và giữ bàn sạch. Có tờ nhãn bị dán lệch, cô giúp bạn gỡ ra rồi thử lại. Giọng cô vẫn bình tĩnh, khiến chúng em không ngại sửa lỗi.

Nhờ cô, góc sách trở thành nơi em muốn ghé thường xuyên. Em quý sự kiên nhẫn và cách cô khuyến khích người đọc tự suy nghĩ. Em mong có thể giữ gìn những cuốn sách cẩn thận như cô, để niềm vui đọc sách đến với nhiều bạn hơn."""

